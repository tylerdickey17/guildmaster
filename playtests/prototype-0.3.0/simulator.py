def round_half_up(n):
    return math.floor(n + .5)

def wage(level):
    return V["pay_rounding"] * round_half_up(V["pay_base"] * V["pay_growth"] ** (level - 1) / V["pay_rounding"])

def rank(level):
    return "legendary" if level >= 17 else "master" if level >= 9 else "expert" if level >= 5 else "trained"

def degree(face, modifier, dc):
    delta = face + modifier - dc
    result = 3 if delta >= 10 else 2 if delta >= 0 else 0 if delta <= -10 else 1
    return max(0, min(3, result + (1 if face == 20 else -1 if face == 1 else 0)))

def keyed_face(seed, *keys):
    """Rejection-sampled SHA256 counter draw, uniform without modulo bias."""
    key = json.dumps([seed, *keys], separators=(",", ":"))
    nonce = 0
    while True:
        digest = hashlib.sha256((key + ":" + str(nonce)).encode()).digest()
        for b in digest:
            if b < 240:
                return b % 20 + 1
        nonce += 1

def cash_multiplier(levels, recommended_level, recommended_size=4):
    average = sum(levels) // len(levels)
    raw = 1 + .1 * (recommended_size - len(levels)) + .1 * (recommended_level - average)
    return max(.5, min(1.5, raw))

def mission(levels, faces, kind="standard", recommended_level=None, profile="high", sparse_support=False,
            essential=None, preparation=0, leader_bonus=0, support_cap=None):
    """Balanced fixture: highest-level NPC leads every phase; declared beforehand.
    Other supporters relevant on every phase unless sparse_support=True (one).
    No NPC is full-sheet generated by this fixture; use live actual skills instead.
    """
    assert 2 <= len(levels) <= 6 and all(1 <= x <= 20 for x in levels)
    card = V["contracts"][kind]
    rec = recommended_level if recommended_level is not None else sum(levels) // len(levels)
    lead = max(range(len(levels)), key=lambda i: levels[i])
    others = [x for i,x in enumerate(levels) if i != lead]
    if sparse_support:
        others = others[:1]
    support = min(support_cap or V["support_cap"], sum(V["support_by_rank"][rank(x)] for x in others))
    skill = V["skill_" + profile][levels[lead]]
    size_dc = max(-2, min(2, 4 - len(levels)))
    dc = V["level_dc"][rec] + card["dc_offset"] + size_dc
    persistent = 0
    next_effect = 0
    outcomes = []
    recovery = card["mandatory_recovery"]
    for p, face in enumerate(faces):
        circumstance = max(preparation if p == 1 else 0, leader_bonus if p == 1 else 0)
        d = degree(face, skill + support + persistent + next_effect + circumstance, dc)
        outcomes.append(d)
        next_effect = 0
        if d == 0:
            persistent -= 2
            recovery = max(recovery, V["critical_failure_recovery"])
        elif d == 1:
            next_effect = -1
        elif d == 3:
            next_effect = 1
    success = sum(d >= 2 for d in outcomes) >= card["required_successes"]
    if essential is not None:
        success = success and outcomes[essential] >= 2
    payout = round_half_up(3 * 4 * wage(rec) * card["payout_factor"] * cash_multiplier(levels, rec)) if success else 0
    return {"success":success,"degrees":outcomes,"recovery":recovery,"cash":payout,
            "wages":sum(wage(l) for l in levels),"recommended_level":rec,"squad_level":sum(levels)//len(levels)}

def exact_mission(levels, **kwargs):
    successes = recoveries = cash = 0
    counts = [0,0,0,0]
    for faces in itertools.product(range(1,21), repeat=3):
        r = mission(levels, faces, **kwargs)
        successes += r["success"]
        recoveries += r["recovery"] > 0
        cash += r["cash"]
        counts[sum(d >= 2 for d in r["degrees"])] += 1
    return {"paths":8000,"success_probability":successes/8000,"recovery_probability":recoveries/8000,
            "expected_cash":cash/8000,"successful_phase_counts":counts}

def campaign(seed=7, turns=12, acquisition_cost=1, initial_mercs=4, initial_merc_level=1,
             initial_guild_level=1, officers=2, treasury=2000, monthly_overhead=150,
             target_roster=8, failed_pay="half", training=True, profile="high",
             kind="standard", officer_capacity=2, promotions=True):
    """Management decisions T1..Tn, then final settlement at Tn+1.
    Summary cash_end follows terminal upkeep/bills; trace includes that boundary.
    Recruitment target fixedL1. All-level replenishing board, matching job chosen
    BEFORE rolling at squad floor average. Officers fixture+10 on admin checks.
    Policy: acquire/deploy full4-person squads first, hire existing candidates,
    search if belowtarget, start spare4person training ifcashreserve800, otherwise
    promote. Consecutive training stops upon next completion to seek work.
    Level5 leaders/feats intentionally omitted; MVP rotates by turn among squad.
    """
    roster = [{"id":i,"level":initial_merc_level,"xp":0,"loyalty":50,"available":1,"inactive":False} for i in range(initial_mercs)]
    candidates=[]; jobs=[]; cohorts=[]; trace=[]
    cash=treasury; arrears=0; rep=0; glevel=initial_guild_level; gxp=0
    completed=failed=deployments=actions_used=unused=blocked=hires=searches=training_blocks=0
    receipts_total=wages_total=training_total=overhead_total=promotion_total=hiring_total=0
    breach=False
    for t in range(1,turns+2):
        start_level=glevel
        earned_guild=0; received=0; paid=0; due_wages=0; pending_loyalty=[]
        results=[]
        for job in [j for j in jobs if j["due"]==t]:
            r=job["result"]; card=V["contracts"][kind]
            received+=r["cash"]; cash+=r["cash"]
            earned_guild+=card["guild_xp"] if r["success"] else 0
            completed+=r["success"]; failed+=not r["success"]
            rep=max(-20,min(100,rep+(card["reputation_success"] if r["success"] else card["reputation_failure"])))
            xp=card["participation_xp"]+(card["completion_xp"] if r["success"] else 0)
            mvp=job["ids"][job["departure"]%len(job["ids"])] if r["success"] else None
            for i in job["ids"]:
                m=roster[i]; m["xp"]+=xp+(50 if i==mvp else 0)
                while m["xp"]>=1000 and m["level"]<20:
                    m["xp"]-=1000;m["level"]+=1
                m["available"]=t+r["recovery"]
            if r["success"]:
                due_wages+=r["wages"]
            else:
                pending_loyalty.append(job)
            results.append({"ids":job["ids"],"success":r["success"],"degrees":r["degrees"],"recovery":r["recovery"],"cash":r["cash"],"quoted_wages":r["wages"]})
        # All client receipts are now present, before ALL wage/overhead obligations.
        owed=arrears+due_wages
        wage_paid=min(cash,owed);cash-=wage_paid;arrears=owed-wage_paid
        paid+=wage_paid;wages_total+=wage_paid
        mandatory=monthly_overhead if t>1 else 0
        overhead_paid=min(cash,mandatory);cash-=overhead_paid
        arrears+=mandatory-overhead_paid;overhead_total+=overhead_paid
        breach=breach or arrears>0
        for job in pending_loyalty:
            fraction={"full":1,"half":.5,"none":0}[failed_pay]
            wanted=round_half_up(job["result"]["wages"]*fraction)
            funded=wanted if cash>=wanted else 0
            cash-=funded;paid+=funded;wages_total+=funded
            mode=failed_pay if funded==wanted else "none"
            for i in job["ids"]:
                m=roster[i];m["loyalty"]=max(0,min(100,m["loyalty"]+V["failed_pay_loyalty"][mode]))
                if m["loyalty"]==0:m["inactive"]=True
        for cohort in [c for c in cohorts if c["due"]==t]:
            training_blocks+=1
            for i in cohort["ids"]:
                m=roster[i];m["xp"]+=150
                while m["xp"]>=1000 and m["level"]<20:m["xp"]-=1000;m["level"]+=1
                m["available"]=t
        candidates=[c for c in candidates if c["expires"]>=t]
        pool=V["guild_actions"][start_level] if t<=turns else 0
        capacity=officers*officer_capacity
        remaining=min(pool,capacity); used=0; decisions=[]
        def spend(n, label):
            nonlocal remaining,used
            if n>remaining:return False
            remaining-=n;used+=n;decisions.append(label);return True
        available=[m["id"] for m in roster if not m["inactive"] and m["available"]<=t]
        if t<=turns:
            while len(available)>=4 and remaining>=acquisition_cost:
                ids=available[:4];available=available[4:]
                spend(acquisition_cost,"Secure Contract" if acquisition_cost else "Free acquisition (A/B)")
                levels=[roster[i]["level"] for i in ids]
                faces=[keyed_face(seed,"mission",t,ids,p) for p in range(3)]
                r=mission(levels,faces,kind=kind,profile=profile)
                jobs.append({"departure":t,"due":t+1,"ids":ids,"result":r})
                for i in ids:roster[i]["available"]=10**9
                deployments+=1
            if available and len(available)>=4:blocked+=len(available)//4
            while candidates and len(roster)<target_roster and cash>=100 and remaining:
                spend(1,"Recruit Operative");cash-=100;hiring_total+=100;hires+=1
                candidates.pop(0);roster.append({"id":len(roster),"level":1,"xp":0,"loyalty":50,"available":t+1,"inactive":False})
            if len(roster)<target_roster and not candidates and remaining:
                spend(1,"Work the Network: recruitment");searches+=1
                count=degree(keyed_face(seed,"search",t),10,15)
                candidates.extend({"expires":t+1} for _ in range(count))
                while candidates and len(roster)<target_roster and cash>=100 and remaining:
                    spend(1,"Recruit Operative");cash-=100;hiring_total+=100;hires+=1;candidates.pop(0)
                    roster.append({"id":len(roster),"level":1,"xp":0,"loyalty":50,"available":t+1,"inactive":False})
            available=[m["id"] for m in roster if not m["inactive"] and m["available"]<=t]
            if training and available and remaining and cash>=800:
                ids=available[:4];cost=50+25*len(ids)
                if cash>=cost:
                    spend(1,"Run Training Drills");cash-=cost;training_total+=cost
                    cohorts.append({"ids":ids,"due":t+1})
                    for i in ids:roster[i]["available"]=10**9
            while promotions and remaining and cash>=850:
                spend(1,"Promote the Guild");cash-=50;promotion_total+=50
                rep=max(-20,min(100,rep+V["promotion_reputation_by_degree"][degree(keyed_face(seed,"promote",t,used),10,V["level_dc"][min(20,2*start_level-1)])]))
        gxp+=earned_guild
        while gxp>=1000 and glevel<10:gxp-=1000;glevel+=1
        receipts_total+=received;actions_used+=used;unused+=remaining
        trace.append({"boundary":t,"terminal":t>turns,"cash":cash,"arrears":arrears,"receipts":received,"wages_paid":paid,"overhead_paid":overhead_paid,"guild_level":glevel,"guild_xp":gxp,"pool":pool,"officer_capacity":capacity,"actions_used":used,"unused_executable":remaining,"decisions":decisions,"settlements":results,"roster_count":len(roster),"levels":[m["level"] for m in roster],"loyalty":[m["loyalty"] for m in roster],"reputation":rep})
    assert cash>=0 and arrears>=0
    return {"version":V["version"],"pack_hash":PACK_HASH,"seed":seed,"turns":turns,"cash_end":cash,"arrears_end":arrears,"ever_arrears":breach,"guild_level":glevel,"guild_xp":gxp,"roster":roster,"completed":completed,"failed":failed,"deployed":deployments,"actions_used":actions_used,"unused_executable":unused,"blocked_squad_turns":blocked,"hires":hires,"searches":searches,"training_blocks":training_blocks,"reputation":rep,"receipts_total":receipts_total,"wages_paid_total":wages_total,"training_cost_total":training_total,"overhead_paid_total":overhead_total,"promotion_cost_total":promotion_total,"hiring_cost_total":hiring_total,"trace":trace}

def wilson(successes, n):
    z=1.959963984540054;p=successes/n;den=1+z*z/n
    mid=(p+z*z/(2*n))/den;span=z*math.sqrt(p*(1-p)/n+z*z/(4*n*n))/den
    return [mid-span,mid+span]

def quantiles(numbers):
    a=sorted(numbers)
    return {str(p):a[max(0,math.ceil(p/100*len(a))-1)] for p in [10,50,90]}

